/**
 * Bundle generator
 * Orchestrates the full bundle generation process
 */

import fs from 'fs'
import path from 'path'
import type { ResolvedConfig } from '../config/types'
import { shouldConvertEsmToCjs } from '../config/loader'
import { generateEntryPoint } from '../generators/entry'
import { stowBundle, type EsmToCjsStats, type StowLanguage } from './stow'
import { validateDependencies, findMissingOptionalPeers, findLegacyRuntime } from '../validators/dependencies'
import { getPackageList } from '../config/packages'
import {
  DEFAULT_OUTPUT_DIR,
  DEFAULT_ENTRY_FILENAME,
  DEFAULT_KOTLIN_PACKAGE,
  DEFAULT_TARGET,
  LEGACY_RUNTIME_PACKAGE,
  PACKAGE_MARKER_FILENAME,
  RUNTIME_OVERRIDE_SPEC
} from '../constants'

const PACKAGE_MARKER_HEADER =
  '# Generated by @tetherto/wdk-worklet-bundler. `generate` deletes what is listed here and writes the package again on every run.'

export type { StowBundleOptions, StowBundleResult, StowLanguage, BareRpcLimits, EsmToCjsStats } from './stow'
export { stowBundle } from './stow'

export interface GenerateBundleOptions {
  dryRun?: boolean
  verbose?: boolean
  silent?: boolean
  skipGeneration?: boolean
  deferOptionalPeers?: boolean
}

export interface GenerateBundleResult {
  success: boolean
  /** Folder of the generated package: the Swift package or the Kotlin module. */
  outputDir: string
  /** The bundle inside the package. Empty until packing succeeded. */
  bundlePath: string
  /** Size of the bundle file written. */
  bundleSize: number
  /** Every file bare-stow wrote into the package. Empty until packing succeeded. */
  files: string[]
  /** ESM→CJS conversion counters, or null when conversion was off or packing did not succeed. */
  esmToCjs: EsmToCjsStats | null
  duration: number
  error?: string
  missingModule?: string
}

/**
 * The language of the host package as bare-stow takes it, from the config.
 */
function stowLanguage (config: ResolvedConfig): StowLanguage {
  return config.language === 'kotlin'
    ? { name: 'kotlin', package: config.kotlinPackage ?? DEFAULT_KOTLIN_PACKAGE }
    : { name: 'swift' }
}

/**
 * Delete what an earlier run wrote into the folder of the generated package,
 * so that nothing of it stays (the client of another transport, the addons of
 * other hosts). Only the paths the marker file of that run lists are deleted,
 * with the folders they leave empty: a file the user added stays.
 *
 * @returns The paths the earlier run listed, relative to the folder.
 * @throws {Error} If the folder holds files and no marker file, so `generate`
 *   did not write it.
 */
function removeGeneratedFiles (outputDir: string): string[] {
  // macOS Finder writes .DS_Store into a folder it shows: an empty folder may hold one.
  const entries = (fs.existsSync(outputDir) ? fs.readdirSync(outputDir) : [])
    .filter((entry) => entry !== '.DS_Store')

  if (entries.length === 0) return []

  if (!entries.includes(PACKAGE_MARKER_FILENAME)) {
    throw new Error(
      `The output folder ${outputDir} holds files that generate did not write, so it is not used. ` +
      "Point 'output' to a folder of its own, or empty this one."
    )
  }

  const root = fs.realpathSync(outputDir)
  const listed = fs.readFileSync(path.join(root, PACKAGE_MARKER_FILENAME), 'utf-8')
    .split('\n')
    .filter((line) => line !== '' && !line.startsWith('#'))

  for (const listedPath of listed) {
    const target = path.join(root, listedPath)
    if (!fs.existsSync(path.dirname(target))) continue

    // A listed path is only followed inside the folder: not out of it with
    // `..`, and not through a link.
    let dir = fs.realpathSync(path.dirname(target))
    if (dir !== root && !dir.startsWith(root + path.sep)) continue

    fs.rmSync(path.join(dir, path.basename(target)), { recursive: true, force: true })

    for (; dir !== root && fs.readdirSync(dir).length === 0; dir = path.dirname(dir)) {
      fs.rmdirSync(dir)
    }
  }

  return listed
}

/**
 * Write the marker file of the package folder, listing what this run wrote.
 */
function writePackageMarker (outputDir: string, written: string[]): void {
  fs.writeFileSync(path.join(outputDir, PACKAGE_MARKER_FILENAME), [PACKAGE_MARKER_HEADER, ...written, ''].join('\n'))
}

/**
 * Generate the WDK worklet package from configuration: write the entry, then
 * have bare-stow pack it and write the Swift package or Kotlin module into
 * `config.outputDir`, replacing what an earlier run wrote there. Failures are
 * reported in the result, not thrown.
 */
export async function generateBundle (
  config: ResolvedConfig,
  options: GenerateBundleOptions = {}
): Promise<GenerateBundleResult> {
  const startTime = Date.now()
  const { dryRun, verbose, silent } = options

  const log = (msg: string): void => {
    if (!silent) console.log(msg)
  }

  const generatedDir = path.join(config.projectRoot, DEFAULT_OUTPUT_DIR)

  const failure = (error: string, missingModule?: string): GenerateBundleResult => ({
    success: false,
    outputDir: config.outputDir,
    bundlePath: '',
    bundleSize: 0,
    files: [],
    esmToCjs: null,
    duration: Date.now() - startTime,
    error,
    ...(missingModule !== undefined ? { missingModule } : {})
  })

  if (dryRun) {
    log(`Dry run - would generate (transport: ${config.transport}, language: ${config.language}):`)
    log(`  Output dir: ${generatedDir}`)
    log(`  Entry: ${generatedDir}/${DEFAULT_ENTRY_FILENAME}`)
    log(`  Package: ${config.outputDir}`)

    return {
      success: true,
      outputDir: config.outputDir,
      bundlePath: '',
      bundleSize: 0,
      files: [],
      esmToCjs: null,
      duration: Date.now() - startTime
    }
  }

  try {
    // The wallet packages bring bare-node-runtime unless something redirects
    // it. The worklet itself runs on bare-wdk-runtime.
    const legacyRuntimeDirs = findLegacyRuntime(config.projectRoot)
    if (legacyRuntimeDirs.length > 0) {
      const engine = config.options?.engine ?? 'v8'
      const where = legacyRuntimeDirs.map((dir) => path.relative(config.projectRoot, dir)).join(', ')
      const fix =
        `Redirect it to bare-wdk-runtime: add "overrides": { "${LEGACY_RUNTIME_PACKAGE}": "${RUNTIME_OVERRIDE_SPEC}" } ` +
        'to package.json and run npm install.'

      if (engine !== 'v8') {
        return failure(`${LEGACY_RUNTIME_PACKAGE} is installed (${where}) and does not run on the '${engine}' engine. ${fix}`)
      }
      log(`  ⚠️  ${LEGACY_RUNTIME_PACKAGE} is installed (${where}), so the bundle carries two runtimes. ${fix}`)
    }

    // Ensure the folder of the generated entry exists
    fs.mkdirSync(generatedDir, { recursive: true })

    // Step 1: Generate the worklet entry point or use the existing one
    let entryPath: string

    if (options.skipGeneration) {
      if (verbose) log('  Skipping artifact generation, using existing files...')

      entryPath = path.join(generatedDir, DEFAULT_ENTRY_FILENAME)

      if (!fs.existsSync(entryPath)) {
        throw new Error(`Artifacts not found at ${entryPath}. Run without --skip-generation first.`)
      }
    } else {
      if (verbose) log('  Generating worklet entry point...')
      entryPath = await generateEntryPoint(config, generatedDir)
      if (verbose) log(`    Entry: ${entryPath}`)
    }

    // Step 2: Pack the module graph and write the host package
    const convertEsmToCjs = shouldConvertEsmToCjs(config)

    // Missing peers marked optional via peerDependenciesMeta (e.g.
    // @ledgerhq/ledger-bitcoin for @bitcoinerlab/descriptors) are deferred so
    // bare-stow doesn't fail statically resolving imports the app never uses.
    // --no-defer-optional-peers disables this for apps that use those
    // features and want to find out at build time instead of runtime.
    let deferredPeers: string[] = []
    if (options.deferOptionalPeers !== false) {
      const { installed } = validateDependencies(getPackageList(config), config.projectRoot)
      deferredPeers = findMissingOptionalPeers(installed, config.projectRoot, { verbose })
      if (deferredPeers.length > 0) {
        log(`  Deferring missing optional peer dependencies: ${deferredPeers.join(', ')}`)
      }
    }

    if (verbose) {
      log(`  Packing for hosts: ${config.options?.targets?.join(', ') ?? `every ${config.language} host`}`)
      if (convertEsmToCjs) log('  Converting ESM to CJS while packing...')
    }

    const writtenBefore = removeGeneratedFiles(config.outputDir)

    let stowed
    try {
      stowed = await stowBundle({
        entry: entryPath,
        out: config.outputDir,
        projectRoot: config.projectRoot,
        target: config.target ?? DEFAULT_TARGET,
        language: stowLanguage(config),
        transport: config.transport,
        limits: {
          maxFrameSize: config.options?.maxFrameSize,
          maxBufferedBytes: config.options?.maxBufferedBytes
        },
        engine: config.options?.engine,
        hosts: config.options?.targets,
        defer: deferredPeers,
        convertEsmToCjs
      })
    } catch (stowError) {
      const errorMsg = stowError instanceof Error ? stowError.message : String(stowError)

      // bare-module-traverse's error carries the unresolved specifier; the
      // CLI turns it into an install hint.
      const { code, specifier, errors } = stowError as { code?: string, specifier?: string, errors?: unknown }
      if (code === 'MODULE_NOT_FOUND' && typeof specifier === 'string') {
        return failure(errorMsg, specifier)
      }

      // esbuild's TransformFailure: a module could not be converted to CommonJS.
      if (Array.isArray(errors)) {
        return failure(`ESM→CJS conversion failed: ${errorMsg}`)
      }

      // Anything else with a code comes from traversing the module graph.
      // Errors without one already say what to do (an invalid output folder
      // name, an unsupported host, a pear-wrk-wdk that is not the RC line).
      if (typeof code !== 'string') {
        return failure(errorMsg)
      }

      return failure(
        `bare-stow failed: ${errorMsg}\n\n` +
        'This usually means:\n' +
        '  1. WDK modules are not installed in the project\n' +
        '  2. A dependency uses Node.js APIs not available in Bare runtime\n\n' +
        'Generated files are available at:\n' +
        `  Entry: ${entryPath}\n` +
        'Fix the dependency and run generate again.'
      )
    } finally {
      // Marked after a failure too, so the next run can replace what this one left.
      if (fs.existsSync(config.outputDir)) {
        writePackageMarker(config.outputDir, stowed === undefined
          ? writtenBefore
          : stowed.files.map((file) => path.relative(config.outputDir, file).split(path.sep).join('/')))
      }
    }

    if (stowed.esmToCjs !== null) {
      log(`  ESM→CJS: converted ${stowed.esmToCjs.converted} JS files, patched ${stowed.esmToCjs.packagesPatched} package.json files`)
    }
    if (verbose) log(`    Package: ${config.outputDir} (${stowed.files.length} files)`)

    return {
      success: true,
      outputDir: config.outputDir,
      bundlePath: stowed.bundlePath,
      bundleSize: fs.statSync(stowed.bundlePath).size,
      files: stowed.files,
      esmToCjs: stowed.esmToCjs,
      duration: Date.now() - startTime
    }
  } catch (error) {
    return failure(error instanceof Error ? error.message : String(error))
  }
}

/**
 * Generate only the entry point
 * Useful for debugging or custom bundling workflows
 */
export async function generateSourceFiles (
  config: ResolvedConfig,
  options: { verbose?: boolean } = {}
): Promise<{ entryPath: string }> {
  const generatedDir = path.join(config.projectRoot, DEFAULT_OUTPUT_DIR)

  if (options.verbose) console.log('  Generating worklet entry point...')
  const entryPath = await generateEntryPoint(config, generatedDir)

  return {
    entryPath
  }
}
